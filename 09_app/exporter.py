# -*- coding: utf-8 -*-
"""数据导出模块：把采集到的原始字节流导出为 CSV / VCD / 二进制文件。

数据格式约定：每个字节代表 8 个通道，CHn 对应 bitn（本机克隆板实测：CH0=bit0 … CH7=bit7）。
所有位提取与跳变检测均使用 numpy 向量化完成，避免逐样本 Python 循环，
保证 100 万样本级别的数据也能在数秒内完成导出。
"""

import os

import numpy as np

# 采样率档位（Hz），供界面与时间戳换算参考
RATES = [24_000_000, 16_000_000, 12_000_000, 8_000_000, 4_000_000,
         2_000_000, 1_000_000, 500_000, 250_000, 200_000]

# VCD 变量标识符：VCD 标准要求单字符，且 ASCII 33('!') 到 126('~') 之间。
# 这里取前 8 个可用字符分别对应 CH1..CH8。
VCD_IDS = '!"#$%&\'('


def _extract_channels(data: bytes, channels: list[int] | None) -> np.ndarray:
    """把原始字节流按选中通道解出 0/1 矩阵，形状 (样本数, 通道数)。

    channels 为 None 时导出全部 8 个通道，通道编号用 1..8（CH1 对应 bit7）。
    """
    raw = np.frombuffer(data, dtype=np.uint8)
    if channels is None:
        channels = list(range(0, 8))
    else:
        channels = list(channels)
        if not channels:
            raise ValueError('channels 不能为空')
        for ch in channels:
            if not 0 <= ch <= 8:
                raise ValueError(f'通道号 {ch} 超出范围 0..7（允许 8 兼容）')
    # CHn -> bitn（ch=8 兼容映射到 bit7）
    shifts = np.asarray([7 if c == 8 else c for c in channels], dtype=np.int32).reshape(1, -1)
    bits = (raw.reshape(-1, 1) >> shifts) & 1
    return bits.astype(np.uint8), channels


def export_csv(path, data: bytes, rate: int, channels: list[int] | None = None,
               mode='samples', time_unit='s'):
    """导出 CSV 文件。

    mode='samples'：每个采样点一行，列 = sample,time,CH1,CH2,...
    mode='changes'：仅任一选中通道跳变时输出一行（含采样点 0 的初始值）。
    time_unit='s' 时 time 列为浮点秒；'samples' 时为整数样本号。
    返回实际写入的行数（含表头）。
    """
    if mode not in ('samples', 'changes'):
        raise ValueError("mode 只能是 'samples' 或 'changes'")
    if time_unit not in ('s', 'samples'):
        raise ValueError("time_unit 只能是 's' 或 'samples'")

    bits, channels = _extract_channels(data, channels)
    n = bits.shape[0]
    time_col = 'time_s' if time_unit == 's' else 'time_samples'
    header = ['sample', time_col] + [f'CH{c}' for c in channels]

    if mode == 'samples':
        rows_idx = np.arange(n, dtype=np.int64)
    else:
        # 任一行内有变化即为跳变：对相邻样本做异或再按行求或
        if n <= 1:
            rows_idx = np.arange(n, dtype=np.int64)
        else:
            changed = np.any(bits[1:] != bits[:-1], axis=1)
            rows_idx = np.concatenate(([0], np.nonzero(changed)[0] + 1)).astype(np.int64)

    parts = []
    parts.append(','.join(header) + '\n')
    samples_str = np.char.mod('%d', rows_idx)
    if time_unit == 's':
        times_str = np.char.mod('%.9g', rows_idx.astype(np.float64) / float(rate))
    else:
        times_str = samples_str
    sel = bits[rows_idx]
    # 逐通道拼成字符串列（通道数固定为 8 以内，非逐样本循环）
    ch_cols = [np.char.mod('%d', sel[:, i]) for i in range(sel.shape[1])]
    lines = np.char.add(samples_str, ',')
    lines = np.char.add(lines, times_str)
    for col in ch_cols:
        lines = np.char.add(lines, ',')
        lines = np.char.add(lines, col)
    parts.append('\n'.join(lines.tolist()) + '\n' if len(lines) else '')

    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(''.join(parts))
    return len(rows_idx) + 1  # 含表头


def export_vcd(path, data: bytes, rate: int, channels: list[int] | None = None,
               timescale='1ns'):
    """导出标准 VCD（Value Change Dump）文件，可被 GTKWave / PulseView 打开。

    timescale 指定输出时间单位（如 '1ns'、'1us'、'1ms'），时间戳按采样率换算：
    第 k 个样本的真实时间为 k/rate 秒，换算为目标单位后取整。
    返回实际写入的行数。
    """
    bits, channels = _extract_channels(data, channels)
    n = bits.shape[0]

    # 时间单位换算：目标单位对应的秒数与采样间隔之比
    unit_seconds = {'1ps': 1e-12, '10ps': 1e-11, '100ps': 1e-10,
                    '1ns': 1e-9, '10ns': 1e-8, '100ns': 1e-7,
                    '1us': 1e-6, '10us': 1e-5, '100us': 1e-4,
                    '1ms': 1e-3, '10ms': 1e-2, '100ms': 1e-1,
                    '1s': 1.0}
    if timescale not in unit_seconds:
        raise ValueError(f'不支持的 timescale: {timescale}')
    factor = (1.0 / rate) / unit_seconds[timescale]  # 样本 -> 时间戳刻度

    lines = []
    lines.append('$date\n   generated by logic analyzer wave_view exporter\n$end')
    lines.append('$version\n   logic analyzer wave_view exporter 1.0\n$end')
    lines.append(f'$timescale\n   {timescale}\n$end')
    lines.append('$comment\n   bit order: CHn=bitn (CH0=bit0 ... CH7=bit7)\n$end')
    lines.append('$scope module logic $end')
    for i, ch in enumerate(channels):
        lines.append(f'$var wire 1 {VCD_IDS[i]} CH{ch} $end')
    lines.append('$upscope $end')
    lines.append('$enddefinitions $end')

    # 初始值块：采样点 0 的所有通道值
    lines.append('$dumpvars')
    for i in range(len(channels)):
        lines.append(f'{int(bits[0, i])}{VCD_IDS[i]}')
    lines.append('$end')

    # 后续变化：逐通道用向量化 diff 找出跳变点，收集 (时间戳, 值, 标识符)
    for i, ch in enumerate(channels):
        col = bits[:, i]
        if n > 1:
            changed_idx = np.nonzero(col[1:] != col[:-1])[0] + 1
        else:
            changed_idx = np.empty(0, dtype=np.int64)
        if len(changed_idx) == 0:
            continue
        stamps = np.rint(changed_idx.astype(np.float64) * factor).astype(np.int64)
        vals = col[changed_idx]
        vid = VCD_IDS[i]
        for ts, val in zip(stamps.tolist(), vals.tolist()):
            lines.append(f'#{ts}')
            lines.append(f'{val}{vid}')

    text = '\n'.join(lines) + '\n'
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    return len(text.splitlines())  # 返回实际物理行数


def export_binary(path, data: bytes):
    """直接把原始字节流写入文件，返回写入的字节数。"""
    with open(path, 'wb') as f:
        f.write(data)
    return len(data)
